"""Build a tiny CFA DNG for decoder tests.

The file is generated by this repository. It is not a photograph and not a
camera sample. License: the same MIT license as the project source.
LibRaw must accept it; the bytes are not taken from raw.pixls.us or any camera.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import tifffile


def write_synthetic_dng(path: Path) -> None:
    """64x64 RGGB, 16-bit, uncompressed, with Make/Model and exposure tags."""
    height = width = 64
    mosaic = np.zeros((height, width), dtype=np.uint16)
    ramp = np.linspace(2000, 40000, (height // 2) * (width // 2), dtype=np.uint16)
    mosaic[0::2, 0::2] = ramp.reshape(height // 2, width // 2)
    mosaic[0::2, 1::2] = 16000
    mosaic[1::2, 0::2] = 15000
    mosaic[1::2, 1::2] = 9000
    matrix = [(value, 10000) for value in (13000, -4000, -1000, -2000, 12000, 0, 0, -3000, 11000)]
    tags = [
        (50706, 1, 4, (1, 4, 0, 0), True),
        (50707, 1, 4, (1, 1, 0, 0), True),
        (50708, 2, None, "Reality First Synthetic\x00", True),
        (271, 2, None, "Reality First\x00", True),
        (272, 2, None, "Synthetic DNG\x00", True),
        (33434, 5, 1, ((1, 125),), True),
        (33437, 5, 1, ((28, 10),), True),
        (34855, 3, 1, (100,), True),
        (33421, 3, 2, (2, 2), True),
        (33422, 1, 4, (0, 1, 1, 2), True),
        (50721, 10, 9, matrix, True),
        (50728, 5, 3, ((1, 1), (1, 1), (1, 1)), True),
        (50714, 5, 1, ((0, 1),), True),
        (50717, 4, 1, (65535,), True),
        (50778, 3, 1, (21,), True),
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    tifffile.imwrite(
        path,
        mosaic,
        photometric=32803,
        planarconfig="contig",
        compression="none",
        metadata=None,
        extratags=tags,
    )
